import io
import zipfile
from typing import Dict, Any
from pcb_copilot.schemas import PCBDesignPlan
from pcb_copilot.kicad_generator import KiCadGenerator
from pcb_copilot.easyeda_generator import EasyEDAGenerator


class ExportEngine:
    """
    Gerber RS-274X, Excellon Drill, BOM, Netlist, and ZIP packaging engine.
    """

    def __init__(self, plan: PCBDesignPlan):
        self.plan = plan

    def generate_bom_csv(self) -> str:
        """Generates standard Bill of Materials (BOM) CSV text."""
        lines = ["Designator,Name,Value,Footprint,PinCount,Layer"]
        for comp in self.plan.components:
            lines.append(
                f'"{comp.designator}","{comp.name}","{comp.value or ""}","{comp.footprint}",{len(comp.pins)},"{comp.layer}"'
            )
        return "\n".join(lines)

    def generate_netlist_text(self) -> str:
        """Generates netlist report text."""
        lines = [f"# Netlist Report for {self.plan.project_title}", "# Generated by PCB-Copilot AI", ""]
        nets: Dict[str, list] = {}
        for comp in self.plan.components:
            for pin in comp.pins:
                if pin.net_name:
                    if pin.net_name not in nets:
                        nets[pin.net_name] = []
                    nets[pin.net_name].append(f"{comp.designator}.{pin.pin_number}({pin.pin_name})")

        for net_name, pins in nets.items():
            lines.append(f"Net {net_name}:")
            for p in pins:
                lines.append(f"  - {p}")
            lines.append("")
        return "\n".join(lines)

    def generate_gerber_rs274x(self, layer_name: str) -> str:
        """
        Generates valid Gerber RS-274X layer format header & primitives.
        """
        bw = self.plan.board_width_mm * 1000  # conversion to microns
        bh = self.plan.board_height_mm * 1000

        lines = [
            "%FSLAX24Y24*%",
            "%MOIN*%",
            f"%IPPOS*%",
            f"%LN{layer_name}*%",
            "%ADD10C,0.2000*%",  # Aperture 10: Circle 0.2mm
            "%ADD11C,1.5000*%",  # Aperture 11: Pad Circle 1.5mm
            "%ADD12R,1.5000X1.5000*%",  # Aperture 12: Rect Pad 1.5x1.5mm
            "G54D10*",
            # Draw board perimeter
            "G00X0Y0D02*",
            f"G01X{int(bw)}Y0D01*",
            f"G01X{int(bw)}Y{int(bh)}D01*",
            f"G01X0Y{int(bh)}D01*",
            "G01X0Y0D01*",
        ]

        # Add component pad flashes
        lines.append("G54D11*")
        for comp in self.plan.components:
            cx = int(comp.x_mm * 1000)
            cy = int(comp.y_mm * 1000)
            lines.append(f"X{cx}Y{cy}D03*")

        lines.append("M02*")
        return "\n".join(lines)

    def generate_excellon_drill(self) -> str:
        """Generates Excellon CNC Drill file format (.drl)."""
        lines = [
            "M48",
            "; DRILL FILE FOR PCB-COPILOT",
            "METRIC,TZ",
            "FMAT,2",
            "T1C0.800",  # Tool 1: 0.8mm for standard pins
            "T2C1.000",  # Tool 2: 1.0mm for power header pins
            "%",
            "G90",
            "G05",
            "T1"
        ]

        for comp in self.plan.components:
            for pin in comp.pins:
                cx = int(comp.x_mm * 1000)
                cy = int(comp.y_mm * 1000)
                lines.append(f"X{cx}Y{cy}")

        lines.append("M30")
        return "\n".join(lines)

    def build_gerber_zip_archive(self) -> bytes:
        """
        Bundles all PCB design outputs (KiCad .kicad_pcb, EasyEDA .json, Gerbers, Drill, BOM) into ZIP archive.
        """
        zip_buffer = io.BytesIO()

        kicad_gen = KiCadGenerator(self.plan)
        easyeda_gen = EasyEDAGenerator(self.plan)

        kicad_pcb_str = kicad_gen.generate_kicad_pcb()
        kicad_sch_str = kicad_gen.generate_kicad_sch()
        easyeda_json_str = easyeda_gen.generate_easyeda_json_string()

        bom_csv = self.generate_bom_csv()
        netlist_txt = self.generate_netlist_text()

        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
            # 1. Native KiCad & EasyEDA Files
            zip_file.writestr("board.kicad_pcb", kicad_pcb_str)
            zip_file.writestr("schematic.kicad_sch", kicad_sch_str)
            zip_file.writestr("easyeda_pcb.json", easyeda_json_str)

            # 2. Reports
            zip_file.writestr("BOM.csv", bom_csv)
            zip_file.writestr("Netlist_Report.txt", netlist_txt)

            # 3. Gerber RS-274X Layers
            zip_file.writestr("gerber_top_copper.gtl", self.generate_gerber_rs274x("Top_Copper"))
            zip_file.writestr("gerber_bottom_copper.gbl", self.generate_gerber_rs274x("Bottom_Copper"))
            zip_file.writestr("gerber_top_soldermask.gts", self.generate_gerber_rs274x("Top_Soldermask"))
            zip_file.writestr("gerber_bottom_soldermask.gbs", self.generate_gerber_rs274x("Bottom_Soldermask"))
            zip_file.writestr("gerber_top_silkscreen.gto", self.generate_gerber_rs274x("Top_Silkscreen"))
            zip_file.writestr("gerber_board_outline.gko", self.generate_gerber_rs274x("Board_Outline"))

            # 4. Drill File
            zip_file.writestr("drill_file.drl", self.generate_excellon_drill())

        return zip_buffer.getvalue()
